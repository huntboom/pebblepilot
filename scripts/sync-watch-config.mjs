#!/usr/bin/env node
/**
 * Writes pebble/src/embeddedjs/config.js from config.json + .env.
 * That file is gitignored — never commit it.
 * PKJS defaults stay placeholder; real phone settings come from Clay.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function loadEnvFile(path) {
  if (!existsSync(path)) return;
  for (const line of readFileSync(path, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq < 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (!(key in process.env)) process.env[key] = value;
  }
}

loadEnvFile(resolve(root, ".env"));

const configPath = process.env.PEBBLEPILOT_CONFIG || resolve(root, "config.json");
const watchConfigPath = resolve(root, "pebble/src/embeddedjs/config.js");

if (!existsSync(configPath)) {
  console.error(`Missing ${configPath}. Copy config.example.json first.`);
  process.exit(1);
}

const config = JSON.parse(readFileSync(configPath, "utf8"));
const token = process.env.PEBBLEPILOT_TOKEN || config.token;
const port = Number(process.env.PEBBLEPILOT_PORT || config.port || 8787);
const lanHost = process.env.PEBBLEPILOT_LAN_HOST;
if (!lanHost) {
  console.error("Set PEBBLEPILOT_LAN_HOST in .env (your LAN/Tailscale IP).");
  process.exit(1);
}

const bindHost = process.env.PEBBLEPILOT_HOST || config.host;
const host =
  bindHost === "0.0.0.0" || bindHost === "127.0.0.1" ? lanHost : bindHost;
const baseUrl = `http://${host}:${port}`;

const next = `/**
 * Daemon connection settings (watch-side status only).
 * Networking is handled in PKJS / Clay — see src/pkjs/.
 *
 * GENERATED by scripts/sync-watch-config.mjs — do not commit.
 */
export const DAEMON_BASE_URL = ${JSON.stringify(baseUrl)};
export const DAEMON_TOKEN = ${JSON.stringify(token)};
export const POLL_MS = ${JSON.stringify(config.pollIntervalMs ?? 8000)};
`;

writeFileSync(watchConfigPath, next);
console.log(`Synced gitignored watch config → ${baseUrl}`);
